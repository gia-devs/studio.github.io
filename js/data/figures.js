export const getFigure = (id) => FIGURES.find((f) => f.id === id) || null;

export const figuresByType = (type) => FIGURES.filter((f) => f.type === type);
export const figuresByStatus = (status) => FIGURES.filter((f) => f.status === status);

export function allDisciplines() {
  return [...new Set(FIGURES.flatMap((f) => f.disciplines))].sort((a, b) => a.localeCompare(b, 'es'));
}

export function allPeriods() {
  return [...new Set(FIGURES.map((f) => f.period))].sort((a, b) => a.localeCompare(b, 'es'));
}

export function topFigures(n = 5) {
  return [...FIGURES].sort((a, b) => b.popularity - a.popularity).slice(0, n);
}

export function similarTo(figure, n = 4) {
  const scored = FIGURES.filter((f) => f.id !== figure.id).map((f) => ({
    f,
    s:
      (f.type === figure.type ? 8 : 0) +
      f.disciplines.filter((d) => figure.disciplines.includes(d)).length * 6 +
      (f.period === figure.period ? 4 : 0) +
      f.popularity / 100,
  }));
  return scored.sort((a, b) => b.s - a.s).slice(0, n).map((x) => x.f);
}

export function fmtYears(years) {
  if (!years) return '';
  const from = years.from < 0 ? `${Math.abs(years.from)} a.C.` : String(years.from);
  if (!years.to) return `${from} –`;
  const to = years.to < 0 ? `${Math.abs(years.to)} a.C.` : String(years.to);
  return `${from} – ${to}`;
}
